const fs = require('fs')
const path = require('path')
const root = path.join(__dirname, '..')
const source = path.join(root, 'node_modules/pdfjs-dist')
const destination = path.join(root, 'public/pdfjs')
fs.mkdirSync(destination, { recursive: true })
for (const name of ['pdf.mjs', 'pdf.worker.mjs']) fs.copyFileSync(path.join(source, 'build', name), path.join(destination, name))
for (const name of ['cmaps', 'standard_fonts', 'wasm']) fs.cpSync(path.join(source, name), path.join(destination, name), { recursive: true })
fs.copyFileSync(path.join(source, 'LICENSE'), path.join(destination, 'LICENSE'))
